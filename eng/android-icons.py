#!/usr/bin/env python3
"""Generate the Android launcher icon, splash drawable and notification icon from the canonical mark.

Usage: python3 eng/android-icons.py assets/branding/mark.svg src/Jourfold.Android/Resources

Android vector drawables take the same path syntax as SVG, so the mark is copied path by path into a 108 dp
adaptive-icon canvas, scaled to stay inside the 66 dp area that every launcher mask keeps. The notification icon is
the mark's silhouette in white on a 24 dp canvas, as Android draws status bar icons in one colour.

The themed icon (Android 13 and newer, when "Themed icons" is on) is ic_launcher_monochrome: the mark's three parts in
three strengths, with the road and the pin left out, as iOS's tinted icon (eng/ios-icons.py). Android uses only its
alpha and tints it in the colours of the home screen; older versions, and the home screen without themed icons, keep
the coloured icon. It is drawn with cairosvg and Pillow, which only this part needs.

The vehicles that ride along the travel day's progress bar (ic_live_*) are the app's own transport icons from
src/Jourfold.UI/Theme/Icons.axaml, drawn white on a disc in Jourfold's accent colour, so they stand out on light and
dark notifications alike.
"""
import sys
import re
import xml.etree.ElementTree as ET
from pathlib import Path

SVG = '{http://www.w3.org/2000/svg}'
source, target = Path(sys.argv[1]), Path(sys.argv[2])
root = ET.parse(source).getroot()
box = float(root.get('viewBox').split()[2])
size = 58.0  # dp of the mark inside the 108 dp canvas
scale = size / box
offset = (108 - size) / 2

paths = []
for p in root.iter(SVG + 'path'):
    fill = p.get('fill', '#000000')
    fill = '#FFFFFF' if fill.lower() in ('#fff', 'white') else fill.upper()
    rule = ' android:fillType="evenOdd"' if p.get('fill-rule') == 'evenodd' else ''
    paths.append(f'    <path android:fillColor="{fill}"{rule} android:pathData="{p.get("d")}"/>')

drawable = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by eng/android-icons.py from assets/branding/mark.svg. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
  <group android:translateX="{offset:g}" android:translateY="{offset:g}" android:scaleX="{scale:.6f}" android:scaleY="{scale:.6f}">
{chr(10).join(paths)}
  </group>
</vector>
'''
(target / 'drawable').mkdir(parents=True, exist_ok=True)
(target / 'drawable' / 'ic_launcher_foreground.xml').write_text(drawable, encoding='utf-8')
(target / 'mipmap-anydpi-v26').mkdir(parents=True, exist_ok=True)
(target / 'mipmap-anydpi-v26' / 'ic_launcher.xml').write_text('''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by eng/android-icons.py. Do not edit. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
  <background android:drawable="@color/launcher_background"/>
  <foreground android:drawable="@drawable/ic_launcher_foreground"/>
  <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
</adaptive-icon>
''', encoding='utf-8')


def monochrome(pixels):
    """The mark for themed icons: white whose alpha is the strength of each part, the white details cut out."""
    import io
    import cairosvg
    from PIL import Image, ImageChops
    text = source.read_text(encoding='utf-8')
    details = re.findall(r'<path fill="#fff"[^>]*/>', text)
    body = text
    for detail in details:
        body = body.replace(detail, '')
    # Three strengths, so the parts stay apart once tinted, as on iOS.
    for old, new in {'#103b5c': '#ffffff', '#45c4af': '#c4c4c4', '#1593a5': '#8c8c8c'}.items():
        body = body.replace(f'fill="{old}"', f'fill="{new}"')
    holes_svg = re.sub(r'(<svg[^>]*>).*(</svg>)', lambda m: m[1] + ''.join(details) + m[2], text, flags=re.S)

    def render(document):
        return Image.open(io.BytesIO(cairosvg.svg2png(bytestring=document.encode('utf-8'), output_width=pixels, output_height=pixels))).convert('RGBA')
    image = render(body)
    alpha = ImageChops.multiply(image.convert('L'), image.getchannel('A'))
    alpha = ImageChops.subtract(alpha, render(holes_svg).getchannel('A'))
    mark = Image.new('RGBA', (pixels, pixels), (255, 255, 255, 0))
    mark.putalpha(alpha)
    return mark


# 108 dp at xxxhdpi (4 px per dp), the mark at the size and place of the coloured foreground.
from PIL import Image  # noqa: E402
canvas = Image.new('RGBA', (432, 432), (255, 255, 255, 0))
inner = round(size * 4)
canvas.alpha_composite(monochrome(inner), (round(offset * 4),) * 2)
(target / 'drawable-xxxhdpi').mkdir(parents=True, exist_ok=True)
canvas.save(target / 'drawable-xxxhdpi' / 'ic_launcher_monochrome.png', optimize=True)

silhouette = [f'    <path android:fillColor="#FFFFFF" android:pathData="{p.get("d")}"/>' for p in root.iter(SVG + 'path')
              if p.get('fill', '#000000').lower() not in ('#fff', 'white')]
small = 22.0 / box
(target / 'drawable' / 'ic_notification.xml').write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by eng/android-icons.py from assets/branding/mark.svg. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">
  <group android:translateX="1" android:translateY="1" android:scaleX="{small:.6f}" android:scaleY="{small:.6f}">
{chr(10).join(silhouette)}
  </group>
</vector>
''', encoding='utf-8')
icons = (Path(__file__).resolve().parent.parent / 'src' / 'Jourfold.UI' / 'Theme' / 'Icons.axaml').read_text(encoding='utf-8')
# Visuals.TransportIcon's icons, which a journey's notification names.
for name in ('plane', 'train-front', 'bus', 'car', 'car-taxi-front', 'ship', 'bike', 'footprints', 'route'):
    data = re.search(rf'<StreamGeometry x:Key="Icon\.{re.escape(name)}">([^<]+)</StreamGeometry>', icons).group(1)
    (target / 'drawable' / f'ic_live_{name.replace("-", "_")}.xml').write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by eng/android-icons.py from the {name} icon in src/Jourfold.UI/Theme/Icons.axaml. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">
  <path android:fillColor="#0F7B7A" android:pathData="M12 0 A12 12 0 1 1 12 24 A12 12 0 1 1 12 0 Z"/>
  <group android:translateX="5" android:translateY="5" android:scaleX="0.583333" android:scaleY="0.583333">
    <path android:strokeColor="#FFFFFF" android:strokeWidth="2.4" android:strokeLineCap="round" android:strokeLineJoin="round" android:pathData="{data}"/>
  </group>
</vector>
''', encoding='utf-8')
print('wrote', target / 'drawable' / 'ic_launcher_foreground.xml', 'the adaptive icon, the notification icon and the vehicles')
