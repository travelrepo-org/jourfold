#!/usr/bin/env python3
"""Generate the Android launcher icon, splash drawable and notification icon from the canonical mark.

Usage: python3 eng/android-icons.py assets/branding/mark.svg src/Jourfold.Android/Resources

Android vector drawables take the same path syntax as SVG, so the mark is copied path by path into a 108 dp
adaptive-icon canvas, scaled to stay inside the 66 dp area that every launcher mask keeps. The notification icon is
the mark's silhouette in white on a 24 dp canvas, as Android draws status bar icons in one colour.
"""
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

SVG = '{http://www.w3.org/2000/svg}'
source, target = Path(sys.argv[1]), Path(sys.argv[2])
root = ET.parse(source).getroot()
box = float(root.get('viewBox').split()[2])
size = 58.0  # dp of the mark inside the 108 dp canvas
scale = size / box
offset = (108 - size) / 2

paths = []
for p in root.iter(SVG + 'path'):
    fill = p.get('fill', '#000000')
    fill = '#FFFFFF' if fill.lower() in ('#fff', 'white') else fill.upper()
    rule = ' android:fillType="evenOdd"' if p.get('fill-rule') == 'evenodd' else ''
    paths.append(f'    <path android:fillColor="{fill}"{rule} android:pathData="{p.get("d")}"/>')

drawable = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by eng/android-icons.py from assets/branding/mark.svg. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
  <group android:translateX="{offset:g}" android:translateY="{offset:g}" android:scaleX="{scale:.6f}" android:scaleY="{scale:.6f}">
{chr(10).join(paths)}
  </group>
</vector>
'''
(target / 'drawable').mkdir(parents=True, exist_ok=True)
(target / 'drawable' / 'ic_launcher_foreground.xml').write_text(drawable, encoding='utf-8')
(target / 'mipmap-anydpi-v26').mkdir(parents=True, exist_ok=True)
(target / 'mipmap-anydpi-v26' / 'ic_launcher.xml').write_text('''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by eng/android-icons.py. Do not edit. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
  <background android:drawable="@color/launcher_background"/>
  <foreground android:drawable="@drawable/ic_launcher_foreground"/>
</adaptive-icon>
''', encoding='utf-8')
silhouette = [f'    <path android:fillColor="#FFFFFF" android:pathData="{p.get("d")}"/>' for p in root.iter(SVG + 'path')
              if p.get('fill', '#000000').lower() not in ('#fff', 'white')]
small = 22.0 / box
(target / 'drawable' / 'ic_notification.xml').write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by eng/android-icons.py from assets/branding/mark.svg. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">
  <group android:translateX="1" android:translateY="1" android:scaleX="{small:.6f}" android:scaleY="{small:.6f}">
{chr(10).join(silhouette)}
  </group>
</vector>
''', encoding='utf-8')
print('wrote', target / 'drawable' / 'ic_launcher_foreground.xml', 'the adaptive icon and the notification icon')
