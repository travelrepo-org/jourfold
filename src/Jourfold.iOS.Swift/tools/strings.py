# Keys that are only formats or debugging probes need no translation.
SKIP = {"", "0", "1", "%@ · %@ ", "%@ – %@", "%@ → %@", "Jourfold", "TravelRepo", "Plus Jakarta Sans", "%lld", "·", "×%@", "≈ %@", "%@ · %@", "%@, %@", "%@ · due %@", "A", "Minimal", "Row", "Scroll", "Tabbed", "Toolbar"}


def unit(lang, value):
    return {lang: {"stringUnit": {"state": "translated", "value": value}}}


def plural(one, other):
    return {"variations": {"plural": {"one": {"stringUnit": {"state": "translated", "value": one}}, "other": {"stringUnit": {"state": "translated", "value": other}}}}}


def main():
    status = 0
    for target in ("Jourfold", "JourfoldWidget", "JourfoldShare"):
        status |= write(target)
    return status


def write(target):
    keys = set()
    for f in glob.glob(os.path.join(ROOT, "build", "**", f"{target}.build", "**", "*.stringsdata"), recursive=True):
        for entries in json.load(open(f)).get("tables", {}).values():
            keys.update(e["key"] for e in entries)
    if target == "Jourfold":
        keys.update(k for k in DE if k in ("Documents", "Clothes", "Electronics"))
    strings = {}
    missing = []
    for k in sorted(keys):
        if k in SKIP and k not in DE:
            strings[k] = {"shouldTranslate": False}
            continue
        if k in PLURAL:
            (en1, en2), (de1, de2) = PLURAL[k]
            strings[k] = {"localizations": {"en": plural(en1, en2), "de": plural(de1, de2)}}
        elif k in DE:
            strings[k] = {"localizations": {"de": {"stringUnit": {"state": "translated", "value": DE[k]}}}}
        else:
            missing.append(k)
            strings[k] = {}
    catalog = {"sourceLanguage": "en", "strings": strings, "version": "1.0"}
    with open(os.path.join(ROOT, target, "Localizable.xcstrings"), "w", encoding="utf-8") as f:
        json.dump(catalog, f, ensure_ascii=False, indent=2, sort_keys=True)
    print(f"{target}: {len(strings)} keys, {len(missing)} without German")
    for k in missing:
        print("  missing:", k)
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
